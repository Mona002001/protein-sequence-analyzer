from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_CENTER
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    PageBreak
)


def generate_pdf(records, output_base):
    """Generate a PDF report for protein analysis."""

    output_path = Path(f"{output_base}.pdf")
    output_path.parent.mkdir(parents=True, exist_ok=True)

    document = SimpleDocTemplate(
        str(output_path),
        pagesize=A4,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "CustomTitle",
        parent=styles["Title"],
        textColor=colors.HexColor("#176B87"),
        alignment=TA_CENTER,
        fontSize=20,
        spaceAfter=20
    )

    heading_style = ParagraphStyle(
        "CustomHeading",
        parent=styles["Heading2"],
        textColor=colors.HexColor("#176B87"),
        spaceBefore=15,
        spaceAfter=10
    )

    story = []

    story.append(
        Paragraph("Protein Sequence Analysis Report", title_style)
    )

    story.append(
        Paragraph(
            "Generated by Protein Sequence Analyzer",
            styles["Normal"]
        )
    )

    story.append(Spacer(1, 20))

    for index, record in enumerate(records):

        if index > 0:
            story.append(PageBreak())

        results = record["results"]

        story.append(
            Paragraph(
                f"Protein ID: {record['protein_id']}",
                heading_style
            )
        )

        story.append(
            Paragraph("Protein Sequence", heading_style)
        )

        story.append(
            Paragraph(
                results["sequence"],
                styles["Code"]
            )
        )

        story.append(Spacer(1, 12))

        story.append(
            Paragraph(
                "Physicochemical Properties",
                heading_style
            )
        )

        property_data = [
            ["Property", "Value"],
            ["Sequence Length", str(results["length"])],
            [
                "Molecular Weight",
                f"{results['molecular_weight']} Da"
            ],
            [
                "Isoelectric Point",
                str(results["isoelectric_point"])
            ],
            ["GRAVY", str(results["gravy"])],
            [
                "Instability Index",
                str(results["instability_index"])
            ],
            ["Aromaticity", str(results["aromaticity"])]
        ]

        property_table = Table(
            property_data,
            colWidths=[250, 220]
        )

        property_table.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0),
                 colors.HexColor("#176B87")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
                ("PADDING", (0, 0), (-1, -1), 8),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1),
                 [colors.white, colors.HexColor("#EAF4F7")])
            ])
        )

        story.append(property_table)

        story.append(
            Paragraph(
                "Amino Acid Composition",
                heading_style
            )
        )

        amino_data = [
            ["Amino Acid", "Count", "Percentage (%)"]
        ]

        for amino_acid, values in results["composition"].items():

            amino_data.append([
                amino_acid,
                str(values["count"]),
                str(values["percentage"])
            ])

        amino_table = Table(
            amino_data,
            colWidths=[150, 150, 170]
        )

        amino_table.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0),
                 colors.HexColor("#176B87")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
                ("ALIGN", (0, 0), (-1, -1), "CENTER"),
                ("PADDING", (0, 0), (-1, -1), 6),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1),
                 [colors.white, colors.HexColor("#EAF4F7")])
            ])
        )

        story.append(amino_table)

    document.build(story)

    print(f"PDF report created: {output_path}")

    return output_path
