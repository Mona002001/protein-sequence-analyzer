
import csv
from pathlib import Path


def generate_tsv(records, output_base):
    """
    Generate a TSV report containing protein analysis results.
    """

    output_path = Path(f"{output_base}.tsv")

    # Create output directory if it does not exist
    output_path.parent.mkdir(parents=True, exist_ok=True)

    fields = [
        "protein_id",
        "sequence_length",
        "molecular_weight",
        "isoelectric_point",
        "gravy",
        "instability_index",
        "aromaticity"
    ]

    amino_acids = "ACDEFGHIKLMNPQRSTVWY"

    # Add amino acid count and percentage columns
    for aa in amino_acids:
        fields.append(f"{aa}_count")
        fields.append(f"{aa}_percentage")

    with open(output_path, "w", newline="", encoding="utf-8") as file:

        writer = csv.DictWriter(
            file,
            fieldnames=fields,
            delimiter="\t"
        )

        writer.writeheader()

        for record in records:

            results = record["results"]

            row = {
                "protein_id": record["protein_id"],
                "sequence_length": results["length"],
                "molecular_weight": results["molecular_weight"],
                "isoelectric_point": results["isoelectric_point"],
                "gravy": results["gravy"],
                "instability_index": results["instability_index"],
                "aromaticity": results["aromaticity"]
            }

            for aa in amino_acids:
                row[f"{aa}_count"] = (
                    results["composition"][aa]["count"]
                )

                row[f"{aa}_percentage"] = (
                    results["composition"][aa]["percentage"]
                )

            writer.writerow(row)

    print(f"\nTSV report created: {output_path}")

    return output_path


